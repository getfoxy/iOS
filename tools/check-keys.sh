#!/bin/sh
# check-keys.sh — no private key material in the tracked sources.
#
#   sh tools/check-keys.sh              scan; exit 1 and print file:line and the hit for each one found
#   sh tools/check-keys.sh --selftest   prove the patterns catch what they should and let the decoys by
#
# What it looks for, in every file git tracks (binary files are skipped):
#   1. a 64-hex-character literal (32 bytes) assigned to a name that contains key, priv, secret,
#      seed or nsec (after ":", "=" or "=>", with or without quotes or a 0x). A name that contains
#      "pub" is a public key and is let by.
#   2. "-----BEGIN ... PRIVATE KEY-----" (PEM, OpenSSH, PGP)
#   3. a Nostr secret key, nsec1...
#   4. an extended private key, xprv... (and yprv, zprv, tprv, uprv, vprv)
#   5. a quoted WIF-looking Bitcoin secret: base58, 51 characters from 5 or 9, or 52 from K, L or c
# (A hard-coded key was found this way once: the signer of a card's time, retired with the card
# software that took it. This is the check that it, or one like it, does not come back.)
#
# Files that are not scanned, each with the reason, are in EXCLUDED below. A hit that is a public
# value is let by in tools/check-keys-allow.txt, one entry per line:
#     <sha256 of the hit text> | reason
#     <path>:<fixed text the hit contains> | reason
# (the hit text is what this script prints after file:line:). A line without a reason is an error.
cd "$(dirname "$0")/.." || exit 1

B58='[1-9A-HJ-NP-Za-km-z]'
P_HEX='[A-Za-z0-9_]*(key|priv|secret|seed|nsec)[A-Za-z0-9_]*["'"'"']?[[:space:]]*(:|=|=>)[[:space:]]*["'"'"'(\[]?[[:space:]]*(0x)?[0-9a-fA-F]{64}([^0-9a-fA-F]|$)'
P_PEM='-----BEGIN [A-Z0-9 ]*PRIVATE KEY'
P_NSEC='nsec1[02-9ac-hj-np-z]{50,}'
P_XPRV='[xyztuv]prv'"$B58"'{100,}'
P_WIF='["'"'"'`](5'"$B58"'{50}|9'"$B58"'{50}|[KLc]'"$B58"'{51})["'"'"'`]'

# EXCLUDED: path prefix, then the reason. These hold published or throwaway values that look like keys.
EXCLUDED='
node_modules/|third-party packages, not ours
Vendor/|vendored libraries, rebuilt from signed tags (tools/rebuild-vendor.sh)
tools/acorn/|the vendored JavaScript parser
build/|build artefacts (generated; build/foxy-app.js is the joined build/app and build/wallet, which are scanned)
Web/foxy-wallet.js|generated from build/wallet, which is scanned
Web/index.html|generated from build/markup.html and the joined sources, which are scanned
tests/snapshots/|rendered screens (generated by tests/render-snapshots.js)
tests/vectors/|the NUT specifications own published test vectors, copied verbatim
tests/fixtures/nip44.vectors.json|the official NIP-44 test vectors (paulmillr/nip44), published
tests/fixtures/nut13-cross.json|made by tools/gen-nut13-cross.js from throwaway test mnemonics for NUT-13 cross checks; no wallet uses them
'

# the two shas: macOS has shasum, Linux has sha256sum
sha() { if command -v shasum >/dev/null 2>&1; then shasum -a 256 | cut -d' ' -f1; else sha256sum | cut -d' ' -f1; fi; }

# hits_of: reads NUL-separated paths on stdin, prints path:line:hit for every pattern
hits_of() {
  list="$(mktemp)"; cat > "$list"
  xargs -0 grep -HInoiE -e "$P_HEX" < "$list" 2>/dev/null | grep -viE '^[^:]*:[0-9]+:[A-Za-z0-9_]*pub[A-Za-z0-9_]*["'"'"']?[[:space:]]*(:|=|=>)'
  xargs -0 grep -HInoE -e "$P_PEM" -e "$P_NSEC" -e "$P_XPRV" -e "$P_WIF" < "$list" 2>/dev/null
  rm -f "$list"
}

if [ "$1" = "--selftest" ]; then
  dir="$(mktemp -d)"; trap 'rm -rf "$dir"' EXIT
  h="0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
  printf 'let privateKeyHex = "%s"\n' "$h"                      > "$dir/1"
  printf 'const SEED = 0x%s;\n' "$h"                             > "$dir/2"
  printf '"secret": "%s"\n' "$h"                                 > "$dir/3"
  printf -- '%s EC PRIVATE KEY-----\n' '-----BEGIN'              > "$dir/4"
  printf 'x = nsec1%s\n' "$(printf 'q%.0s' $(seq 1 58))"       > "$dir/5"
  printf 'k = xprv%s\n' "$(printf '9%.0s' $(seq 1 107))"         > "$dir/6"
  printf 'w = "5%s"\n' "$(printf 'H%.0s' $(seq 1 50))"           > "$dir/7"
  printf 'w = "L%s"\n' "$(printf 'h%.0s' $(seq 1 51))"           > "$dir/8"
  printf 'let publicKeyHex = "%s"\n' "$h"                        > "$dir/d1"   # public: let by
  printf 'let digest = "%s"\n' "$h"                              > "$dir/d2"   # not a key name
  printf 'let seedLabel = "FoxyCard/time"\n'                     > "$dir/d3"
  printf 'let key = "%s0"\n' "$h"                                > "$dir/d4"   # 65 hex: not 32 bytes
  printf 'ur:bytes/1-2/%s\n' "$(printf 'lpcs%.0s' $(seq 1 30))"  > "$dir/d5"
  bad=0
  for f in 1 2 3 4 5 6 7 8; do
    [ -n "$(printf '%s\0' "$dir/$f" | hits_of)" ] || { echo "SELFTEST: pattern $f found nothing"; bad=1; }
  done
  for f in d1 d2 d3 d4 d5; do
    [ -z "$(printf '%s\0' "$dir/$f" | hits_of)" ] || { echo "SELFTEST: decoy $f was flagged"; bad=1; }
  done
  [ "$bad" = 0 ] && echo "check-keys self-test: 8 patterns found, 5 decoys let by"
  exit "$bad"
fi

allowed=0
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
git ls-files -z | hits_of | sort -u > "$tmp"

found=0
while IFS= read -r line; do
  [ -n "$line" ] || continue
  path="${line%%:*}"
  # excluded paths
  skip=0
  while IFS='|' read -r prefix reason; do
    [ -n "$prefix" ] || continue
    case "$path" in "$prefix"*) skip=1; break ;; esac
  done <<EOT
$EXCLUDED
EOT
  [ "$skip" = 1 ] && continue
  rest="${line#*:}"; text="${rest#*:}"
  digest="$(printf '%s' "$text" | sha)"
  # the allowlist
  ok=0
  if [ -f tools/check-keys-allow.txt ]; then
    while IFS= read -r entry; do
      case "$entry" in ''|'#'*) continue ;; esac
      pat="${entry%% | *}"; why="${entry#* | }"
      if [ "$pat" = "$entry" ] || [ -z "$why" ]; then echo "tools/check-keys-allow.txt: an entry has no reason: $entry"; exit 1; fi
      if [ "$pat" = "$digest" ]; then ok=1; break; fi
      case "$pat" in
        *:*) epath="${pat%%:*}"; etext="${pat#*:}"
             if [ "$epath" = "$path" ]; then case "$text" in *"$etext"*) ok=1; break ;; esac; fi ;;
      esac
    done < tools/check-keys-allow.txt
  fi
  if [ "$ok" = 1 ]; then allowed=$((allowed + 1)); continue; fi
  echo "$path:${rest%%:*}: $text"
  found=$((found + 1))
done < "$tmp"

if [ "$found" -gt 0 ]; then
  echo
  echo "check-keys: $found possible private key(s) in tracked sources. Remove it, or if it is a public value add it to tools/check-keys-allow.txt with the reason."
  exit 1
fi
echo "check-keys: no private key material in the tracked sources ($allowed allowlisted)"
